# Weak "red herring" lines from OTHER incident types (WARN level).
HERRINGS = {
    "deploy_regression": "autoscaler: deploy window opens at 02:00 (no change pending) slot={n}",
    "flaky_test": "ci: slow test detected tests/test_misc.py took {n}.1s",
    "dependency_outage": "health probe timed out for cache-sidecar attempt {n} (recovered)",
    "config_drift": "config lint warning: key legacy_flag_{n} unused",
    "db_connection_exhaustion": "slow query {ms}ms on reporting replica",
    "memory_leak": "minor GC pause {ms}ms",
}


def _fields(rng):
    maj, mi, pa = rng.randint(1, 4), rng.randint(0, 9), rng.randint(2, 20)
    mod = rng.choice(MODS)
    dep = rng.choice(DEPS)
    n = rng.randint(20, 50)
    return dict(
        svc=rng.choice(SERVICES), dep=dep, depf=dep.replace("-", "_"),
        ver="v%d.%d.%d" % (maj, mi, pa), prev="v%d.%d.%d" % (maj, mi, pa - 1),
        mod=mod, key=rng.choice(KEYS), old=rng.choice([30, 50, 100]),
        new=rng.choice([9999, 0, 777777]), n=n, w=rng.randint(20, 60),
        pct=rng.randint(12, 48), ms=rng.randint(300, 900), field=rng.choice(FIELDS),
        ep=rng.choice(EPS), host="10.%d.%d.%d" % (rng.randint(0, 9), rng.randint(0, 9), rng.randint(1, 250)),
        port=rng.choice([443, 6379, 9092]), mb=rng.choice([512, 1024, 2048]),
        r=rng.randint(2, 9), k=rng.randint(2, 8),
        test="test_%s_%s" % (mod, rng.choice(["totals", "roundtrip", "ordering", "expiry"])),
        ln1=rng.randint(20, 120), ln2=rng.randint(130, 400), ln3=rng.randint(10, 90),
    )


def _fmt(t, f, **extra):
    d = dict(f)
    d.update(extra)
    return t.format(**d)


# --- tool-result builders -----------------------------------------------------
def _build_log(rng, f, spec, incident):
    N = rng.randint(160, 260)
    chain, outl = spec["chain"], spec["outliers"]
    herr_types = rng.sample([t for t in INCIDENT_TYPES if t != incident], 2)
    n_special = len(chain) + len(outl) + 4
    pool = rng.sample(range(N // 4, N - 3), n_special)
    chain_pos = sorted(pool[:len(chain)])
    outl_pos = pool[len(chain):len(chain) + len(outl)]
    herr_pos = pool[len(chain) + len(outl):]
    msgs = []
    for _ in range(N):
        r = rng.random()
        if "subtle_noise" in spec and r < 0.10:
            lvl, svc, m = "INFO", f["svc"], _fmt(spec["subtle_noise"], f, a=rng.randint(5, 30),
                                                 i=rng.randint(20, 45), h=rng.randint(300, 900),
                                                 g=rng.randint(8, 60))
        elif r < 0.45:
            lvl, svc, m = "INFO", f["svc"], "GET /api/%s 200 %dms" % (rng.choice(EPS), rng.randint(3, 90))
        elif r < 0.70:
            lvl, svc, m = "INFO", f["svc"], "POST /api/%s 201 %dms" % (rng.choice(EPS), rng.randint(3, 90))
        elif r < 0.85:
            lvl, svc, m = "INFO", "monitor", "healthcheck ok"
        elif r < 0.95:
            lvl, svc, m = "INFO", "scheduler", "scheduler tick ok queue=%d" % rng.randint(0, 40)
        else:
            lvl, svc, m = "INFO", f["svc"], "cache hit ratio=%d%%" % rng.randint(80, 99)
        msgs.append([lvl, svc, m, None])
    for pos, item in zip(chain_pos, chain):
        msgs[pos] = [item[0], _fmt(item[1], f), _fmt(item[2], f), "chain"]
    for pos, item in zip(outl_pos, outl):
        msgs[pos] = [item[0], _fmt(item[1], f), _fmt(item[2], f), "outlier"]
    for j, pos in enumerate(herr_pos):
        t = herr_types[j // 2]
        msgs[pos] = ["WARN", "monitor", _fmt(HERRINGS[t], f, n=rng.randint(2, 9), ms=rng.randint(120, 400)), None]
    sec = 8 * 3600 + rng.randint(0, 3000)
    lines = ["# " + BANNER + " | tool=kubectl logs"]
    evidence = []
    for lvl, svc, m, kind in msgs:
        sec += rng.randint(1, 3)
        line = "2026-03-%02d %02d:%02d:%02d %-5s %s %s" % (
            rng.randint(1, 1) + 10, sec // 3600 % 24, sec // 60 % 60, sec % 60, lvl, svc, m)
        lines.append(line)
        if kind:
            evidence.append({"type": "log", "kind": kind, "line": line})
    return "\n".join(lines), evidence


def _build_test(rng, f, spec):
    et, msg_t, code_t = spec["test"]
    msg = _fmt(msg_t, f)
    M = rng.randint(60, 110)
    mod, test = f["mod"], f["test"]
    lines = ["# " + BANNER + " | tool=pytest",
             "============ test session starts ============",
             "platform linux -- Python 3.12.0", "collected %d items" % (M + 1)]
    for _ in range(M):
        lines.append("tests/test_%s_%d.py::test_case_%d PASSED" % (rng.choice(NOISE_WORDS), rng.randint(1, 30), rng.randint(1, 9)))
    t_file, s_file = "tests/test_%s.py" % mod, "src/%s.py" % mod
    frame = '  File "%s", line %d, in %s' % (s_file, f["ln2"], "run_" + mod)
    loc = "%s:%d: %s" % (t_file, f["ln1"], et)
    failed = "FAILED %s::%s - %s: %s" % (t_file, test, et, msg)
    lines += ["================ FAILURES ================", "____ %s ____" % test, "",
              "Traceback (most recent call last):",
              '  File "%s", line %d, in %s' % (t_file, f["ln1"], test),
              "    result = run_%s(payload)" % mod,
              frame, "    " + _fmt(code_t, f),
              "%s: %s" % (et, msg), loc]
    evid = [("trace", frame), ("location", loc), ("failure", failed)]
    lines += ["=========== short test summary info ===========", failed]
    if spec.get("rerun"):
        rr = "%s::%s RERUN (1/2)" % (t_file, test)
        ok = "%s::%s PASSED (on rerun 2/2)" % (t_file, test)
        lines += [rr, ok]
        evid += [("rerun", rr), ("rerun", ok)]
    lines.append("=========== 1 failed, %d passed in 3.14s ===========" % M)
    lines.append("exit status: 1")
    evid.append(("exit", "exit status: 1"))
    return "\n".join(lines), [{"type": "test", "kind": k, "line": l} for k, l in evid]


def _build_search(rng, f, spec):
    blocks = []
    paths = ["src/%s_%d.py" % (rng.choice(NOISE_WORDS), rng.randint(1, 9)) for _ in range(6)]
    for _ in range(rng.randint(25, 45)):
        p, ln = rng.choice(paths), rng.randint(5, 400)
        blocks.append(["%s-%d-    ctx" % (p, ln - 1), "%s:%d:%s" % (p, ln, rng.choice(SEARCH_NOISE)),
                       "%s-%d-    ctx" % (p, ln + 1), "--"])
    for _ in range(rng.randint(8, 15)):
        p, ln = "vendor/lib%d/core.py" % rng.randint(1, 4), rng.randint(5, 900)
        blocks.append(["%s:%d:%s" % (p, ln, rng.choice(SEARCH_NOISE)), "--"])
    p1, p2 = "src/%s.py" % f["mod"], _fmt(spec["search_path2"], f)
    ev = [(p1, f["ln2"], _fmt(spec["search"][0], f)), (p2, f["ln3"], _fmt(spec["search"][1], f))]
    for path, ln, text in ev:
        blocks.insert(rng.randint(0, len(blocks)), ["%s-%d-    ctx" % (path, ln - 1), "%s:%d:%s" % (path, ln, text),
                                                     "%s-%d-    ctx" % (path, ln + 1), "--"])
    lines = ["# " + BANNER + " | tool=ripgrep", "$ rg -n -C1 '%s'" % f["mod"]]
    for b in blocks:
        lines += b
    return "\n".join(lines), [{"type": "search", "kind": "ref", "line": "%s:%d" % (p, ln)} for p, ln, _ in ev]


def _build_tree(rng, f, spec):
    mark_dir, mark_t = spec["tree"]
    mark = _fmt(mark_t, f)
    lines = ["# " + BANNER + " | tool=tree", "repo/"]
    for d in ["src", "tests", "config", "deploy", "vendor"]:
        lines.append("  %s/" % d)
        names = ["%s_%d.py" % (NOISE_WORDS[j % 6], j) for j in range(rng.randint(6, 14))]
        if d == mark_dir:
            names.insert(rng.randint(0, len(names)), mark)
        for nm in names:
            lines.append("    " + nm)
    return "\n".join(lines), [{"type": "tree", "kind": "struct", "line": mark}]


def _build_api(rng, f, spec):
    item = spec["api"](f)
    names = rng.sample(SERVICES + DEPS, 9) + ["svc-%d" % i for i in range(rng.randint(4, 8))]
    items = [{"name": nm, "replicas": 3, "status": "healthy", "version": "v1.%d.0" % rng.randint(0, 9)} for nm in names]
    items.insert(rng.randint(3, len(items) - 2), item)
    ev = json.dumps(item, sort_keys=True)
    lines = ["# " + BANNER + " | tool=http GET", "GET /v1/services -> 200",
             '{"endpoint": "/v1/services", "items": [']
    for i, it in enumerate(items):
        lines.append(" " + json.dumps(it, sort_keys=True) + ("," if i < len(items) - 1 else ""))
    lines.append('], "total": %d}' % len(items))
    return "\n".join(lines), [{"type": "api", "kind": "struct", "line": ev}]


def build_session(incident, k):
    rng = random.Random("capsule-check/%s/%d" % (incident, k))
    f = _fields(rng)
    spec = SPEC[incident]
    results, evidence = [], []
    for rid, rtype, tool, builder in [
        ("r1", "log", "kubectl logs", lambda: _build_log(rng, f, spec, incident)),
        ("r2", "test", "pytest", lambda: _build_test(rng, f, spec)),
        ("r3", "search", "ripgrep", lambda: _build_search(rng, f, spec)),
        ("r4", "tree", "tree", lambda: _build_tree(rng, f, spec)),
        ("r5", "api", "http GET", lambda: _build_api(rng, f, spec)),
    ]:
        text, ev = builder()
        results.append({"id": rid, "type": rtype, "tool": tool, "text": text})
        for e in ev:
            e["result_id"] = rid
            evidence.append(e)
    return {
        "synthetic": True,
        "banner": BANNER,
        "session_id": "%s-%02d" % (incident, k),
        "incident_type": incident,
        "root_cause": incident,
        "candidates": list(INCIDENT_TYPES),
        "tool_results": results,
        "minimal_evidence": evidence,
    }


def build_sessions(per_type=SESSIONS_PER_TYPE):
    return [build_session(t, k) for t in INCIDENT_TYPES for k in range(per_type)]


def write_dataset(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    for s in build_sessions():
        with open(os.path.join(out_dir, s["session_id"] + ".json"), "w") as fh:
            json.dump(s, fh, indent=2, sort_keys=True)
    return out_dir


if __name__ == "__main__":
    print("wrote", write_dataset(sys.argv[1] if len(sys.argv) > 1 else "data/sessions"))
